export function measureText(text: string, scale = 1): number {
  if (!text.length) return 0;
  return text.length * 6 * scale - scale;
}

export function drawText(
  fb: EinkFramebuffer,
  x: number,
  y: number,
  text: string,
  scale = 1,
  ink = true,
): void {
  let cursorX = x;
  for (const ch of text) {
    const glyph = GLYPHS[ch] ?? GLYPHS["?"];
    for (let col = 0; col < 5; col++) {
      const colBits = glyph[col];
      for (let row = 0; row < 8; row++) {
        if ((colBits & (1 << row)) !== 0) {
          for (let dy = 0; dy < scale; dy++) {
            for (let dx = 0; dx < scale; dx++) {
              fb.setPixel(cursorX + col * scale + dx, y + row * scale + dy, ink);
            }
          }
        }
      }
    }
    cursorX += 6 * scale;
  }
}

export function drawTextCentered(
  fb: EinkFramebuffer,
  centerX: number,
  y: number,
  text: string,
  scale = 1,
  ink = true,
): void {
  const w = measureText(text, scale);
  drawText(fb, Math.round(centerX - w / 2), y, text, scale, ink);
}
